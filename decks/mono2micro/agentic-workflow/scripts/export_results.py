#!/usr/bin/env python3
"""Export the final-benchmark results used by the results slides into ext/resultsData.js.

Every number on the results slides comes from
studies/final-benchmark-v1/analysis/final-benchmark-analysis.json (produced by
tools/analyze_final_benchmark.py). Run from the repository root:

    python3 presentations/agentic-workflow/scripts/export_results.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
A = json.loads((ROOT / "studies/final-benchmark-v1/analysis/final-benchmark-analysis.json").read_text())
OUT = Path(__file__).resolve().parents[1] / "ext/resultsData.js"

MODELS = ["deepseek-v4.1-flash", "glm-5.2", "gpt-oss:120b", "gemma4:31b"]
ARMS = [("80k", "80k"), ("OpenCode-B3", "oc"), ("Final", "wf")]
KEYS = [("CMod", "CMod"), ("CiD", "CiD"), ("DTP", "DTP"), ("DI", "DI"), ("BCP", "BCP"),
        ("c2c_cvg 10%", "C2C10"), ("c2c_cvg 33%", "C2C33"), ("c2c_cvg 50%", "C2C50")]
r1 = lambda v: None if v is None else round(v, 1)

main = []
for m in MODELS:
    for arm, short in ARMS:
        d = A["metrics"][m][arm]
        # Recompute means from the full-precision per-system values (the stored means are
        # rounded to 3 decimals, which can flip the 1-decimal rounding, e.g. 55.9495 → 55.95).
        rows = [v for v in d["per_system"].values() if v.get("valid")]
        mv = {src: sum(r[src] for r in rows) / len(rows) for src in [*(k for k, _ in KEYS), "partition_count"]}
        main.append({
            "model": m, "arm": short, "valid": d["valid"],
            **{k: r1(mv[src]) for src, k in KEYS},
            "services": r1(mv["partition_count"]),
            "tokensK": r1(d["tokens_mean_all_attempts"] / 1000),
        })

def paired(block):
    out = {}
    for src, k in [*KEYS, ("tokens", "tokens")]:
        p = block[src]
        out[k] = {"w": p["wins"], "t": p["ties"], "l": p["losses"], "n": p["n_pairs"],
                  "delta": round(p["mean_difference"] / (1000 if k == "tokens" else 1), 2),
                  "p": p["wilcoxon_p"], "cd": p["cliffs_delta"]}
    return out

abl = {k: {"delta": round(A["ablation_vmeasure_vs_final"][src]["mean_difference_final_minus_vmeasure"], 2),
           "w": A["ablation_vmeasure_vs_final"][src]["wins"], "l": A["ablation_vmeasure_vs_final"][src]["losses"],
           "p": A["ablation_vmeasure_vs_final"][src].get("wilcoxon_p"), "n": A["ablation_vmeasure_vs_final"][src]["n"]}
       for src, k in [*KEYS, ("partition_count", "services")]}

tools = {k: r1(A["traditional_tools"]["mean_over_systems"][src]) for src, k in KEYS}
def arm_mean(arm, src):
    means = []
    for m in MODELS:
        rows = [v for v in A["metrics"][m][arm]["per_system"].values() if v.get("valid")]
        means.append(sum(r[src] for r in rows) / len(rows))
    return round(sum(means) / len(means), 1)
vs_tools = [{"arm": "tools", **tools}] + [{"arm": s, **{k: arm_mean(a, src) for src, k in KEYS}} for a, s in [("80k", "80k"), ("Final", "wf")]]

st = A["stability_deepseek_5_repetitions"]
SYS = ["demo", "jpetstore", "partsunlimited", "spring-petclinic"]
stability = [{"arm": s, **{sys: st[a]["per_system"][sys]["unique_partitions"] for sys in SYS},
              "mean": st[a]["mean_unique_partitions"], "nvi": st[a]["mean_pairwise_nvi"]} for a, s in ARMS]
conv = {sys: {"all": A["convergence"][sys]["unique_partitions_all_arms_models"],
              "k80": A["convergence"][sys]["80k_unique_across_models"],
              "wf": A["convergence"][sys]["final_unique_across_models"],
              "wfEq80k": len(A["convergence"][sys]["final_equals_80k_same_model"])} for sys in SYS}

ref = A["refiner"]
refiner = {"runsWithMoves": ref["runs_with_moves"], "runs": ref["runs"],
           "delta": {k: round(ref["blinded_delta_after_refinement_mean"][src], 2) for src, k in KEYS}}

val = A["validity"]
validity = {s: val["all_observations"][a] for a, s in ARMS}
invalid = [{"model": x["model"], "system": x["system"], "services": x["service_count"],
            "missing": x["missing"], "violations": x["violations"]} for x in val["invalid"]]

stages = {k: {"tokens": v["mean_tokens"], "share": v["share"]} for k, v in A["tokens_agentic_stage_breakdown"].items() if k != "other"}

data = {"source": "studies/final-benchmark-v1/analysis/final-benchmark-analysis.json",
        "main": main, "pairedVs80k": paired(A["paired_final_vs_80k"]), "pairedVsOC": paired(A["paired_final_vs_opencode_b3"]),
        "ablation": abl, "vsTools": vs_tools, "stability": stability, "convergence": conv,
        "refiner": refiner, "validity": validity, "invalid": invalid, "stages": stages}
OUT.write_text("// Generated by scripts/export_results.py from " + data["source"] + ". Do not edit by hand.\n"
               "export const R = " + json.dumps(data, indent=1) + "\n")
print("wrote", OUT)
